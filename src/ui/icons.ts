export function iconMarkup(name: string, size = 24): string {
  const key = P[name] ? name : ALIASES[name] && P[ALIASES[name]] ? ALIASES[name] : 'other';
  return `<svg class="icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${P[key]}</svg>`;
}

export function icon(name: string, size = 24): SVGSVGElement {
  const tpl = document.createElement('template');
  tpl.innerHTML = iconMarkup(name, size);
  return tpl.content.firstElementChild as SVGSVGElement;
}

export function hasIcon(name: string): boolean {
  return Boolean(P[name] || (ALIASES[name] && P[ALIASES[name]]));
}

